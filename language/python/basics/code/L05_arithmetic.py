# + - * / // % **
# / 는 항상 float. 정수 나눗셈은 // .

a = 10
b = 3

print(a + b)   # 13
print(a - b)   # 7
print(a * b)   # 30
print(a / b)   # 3.333...  (실수 나눗셈)
print(a // b)  # 3         (정수 나눗셈, 몫)
print(a % b)   # 1         (나머지)
print(a ** b)  # 1000      (거듭제곱)
