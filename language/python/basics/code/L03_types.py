# [문법] 기본 타입
#
# 실행: python L03_types.py
#
# int, float, bool, str 을 가장 많이 쓴다.
# type(값) 으로 타입을 확인할 수 있다.

count = 42          # int (정수)
height = 175.5      # float (실수)
ok = True           # bool (True / False)
name = "리코"       # str (문자열)

print(type(count), count)
print(type(height), height)
print(type(ok), ok)
print(type(name), name)
